  var cache = {};

  function norm(s) {
    return s.replace(/[，。、；：？！\s“”‘’"'…—·「」《》（）()]/g, '');
  }

  function push(out, seen, s, maxLen) {
    s = String(s || '').replace(/^[\s、，。；：？！]+|[\s、，。；：？！]+$/g, '');
    if (!s) return;
    if (s.length < 3 || s.length > maxLen) return;
    var k = norm(s);
    if (!k || k.length < 3 || seen[k]) return;
    seen[k] = 1;
    out.push(s);
  }

  /* 把诗词按句读切成短句，作为弹幕语料 */
  function all(maxLen) {
    maxLen = maxLen || 18;
    if (cache[maxLen]) return cache[maxLen];
    var out = [], seen = {};
    BASE.forEach(function (s) { push(out, seen, s, maxLen); });

    var P = (window.MaoPoems && window.MaoPoems.data) || [];
    P.forEach(function (poem) {
      poem.p.forEach(function (line) {
        line.split(/[，。；：？！、]/).forEach(function (c) {
          push(out, seen, c, maxLen);
        });
      });
      var name = poem.t.replace(/^[^·]*·/, '').replace(/（.*?）/g, '');
      push(out, seen, name, maxLen);
    });
    cache[maxLen] = out;
    return out;
  }

  return { all: all, count: function (n) { return all(n).length; } };
